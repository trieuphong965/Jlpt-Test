def targets(n, rnd):
    seq, pool = [], []
    while len(seq) < n:
        if not pool: pool = [1, 2, 3, 4]; rnd.shuffle(pool)
        c = pool.pop()
        if len(seq) >= 2 and seq[-1] == c and seq[-2] == c:
            pool.insert(0, c)
            if len(pool) == 1: pool = [1, 2, 3, 4]; rnd.shuffle(pool)
            continue
        seq.append(c)
    return seq

