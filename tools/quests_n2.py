def balanced_targets(n, rnd):
    seq, last, run = [], None, 0
    pool = []
    while len(seq) < n:
        if not pool: pool = [1, 2, 3, 4]; rnd.shuffle(pool)
        c = pool.pop()
        if c == last and run >= 2:
            pool.insert(0, c)
            if len(pool) == 1: pool = [1, 2, 3, 4]; rnd.shuffle(pool)
            continue
        run = run + 1 if c == last else 1
        last = c; seq.append(c)
    return seq

def build():
    rnd = random.Random(20261124)
    out = {"level": "N2", "title": "Quest ôn tập N2",
           "groups": [{"id": "kanji", "title": "漢字・語彙", "desc": "Đọc, viết chữ Hán và cấu tạo từ"},
                      {"id": "bunpou", "title": "文法", "desc": "Mẫu ngữ pháp N2 theo chủ đề"}],
           "quests": []}
    for q in QUESTS:
        targets = balanced_targets(len(q["items"]), rnd)
        items = []
        for i, (raw, t) in enumerate(zip(q["items"], targets)):
            iid = f"N2-{q['id']}-{i+1:02d}"
            if "frags" in raw:
                star = raw["frags"][raw["star"]]
                others = [f for j, f in enumerate(raw["frags"]) if j != raw["star"]]
                rnd.shuffle(others)
                opts = others[:]; opts.insert(t - 1, star)
                items.append({"id": iid, "type": "narabe", "stem": raw["stem"], "opts": opts, "ans": t,
                              "exp": "Thứ tự đúng: " + " → ".join(raw["frags"]) + f"（★ = {star}）. " + raw["exp"],
                              "tag": "".join(raw["frags"])})
            else:
                correct = raw["opts"][0]
                others = raw["opts"][1:]; rnd.shuffle(others)
                opts = others[:]; opts.insert(t - 1, correct)
                tag = raw["tag"] or (re.search(r"<u>(.*?)</u>", raw["stem"]) or [None, correct])[1]
                items.append({"id": iid, "type": q["kind"], "stem": raw["stem"], "opts": opts, "ans": t,
                              "exp": raw["exp"], "tag": tag})
        out["quests"].append({k: q[k] for k in ("id", "group", "kind", "title", "desc")} | {"items": items})
    path = os.path.join(ROOT, "public/quests/N2.json")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    json.dump(out, open(path, "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    n = sum(len(q["items"]) for q in out["quests"])
    from collections import Counter
    print(f"{len(out['quests'])} quest, {n} câu, đáp án:", dict(sorted(Counter(i['ans'] for q in out['quests'] for i in q['items']).items())))

